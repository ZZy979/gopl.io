package exec3_10

import "testing"

func TestComma(t *testing.T) {
	testCases := []struct {
		s        string
		expected string
	}{
		{"", ""},
		{"1", "1"},
		{"12", "12"},
		{"123", "123"},
		{"1234", "1,234"},
		{"1234567890", "1,234,567,890"},
		{"-2", "-2"},
		{"+3", "+3"},
		{"-123456", "-123,456"},
		{"+1234567890", "+1,234,567,890"},
		{"-1234567890", "-1,234,567,890"},
		{"12345.", "12,345."},
		{"0.1234", "0.1234"},
		{"+0.12345", "+0.12345"},
		{"-123456789.987654321", "-123,456,789.987654321"},
	}
	for _, tc := range testCases {
		if r := Comma(tc.s); r != tc.expected {
			t.Errorf("Comma(%q) = %q, want %q", tc.s, r, tc.expected)
		}
	}
}
